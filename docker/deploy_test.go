package docker_test

import (
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

func TestDeployRollsBackApplicationAndMonitoring(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("requires Unix shell paths")
	}
	root := t.TempDir()
	old := filepath.Join(root, "old")
	next := filepath.Join(root, "next")
	bin := filepath.Join(root, "bin")
	for _, dir := range []string{old, next, bin} {
		if err := os.MkdirAll(dir, 0700); err != nil {
			t.Fatal(err)
		}
	}
	for _, dir := range []string{old, next} {
		for _, name := range []string{"compose.yaml", "compose.observability.yaml", "compose.observability.production.yaml"} {
			if err := os.WriteFile(filepath.Join(dir, name), nil, 0600); err != nil {
				t.Fatal(err)
			}
		}
	}
	for name, value := range map[string]string{".env": "STORAGE_WRITE_LEGACY=true\n", "current-image": "old-image\n", "current-release": old + "\n"} {
		if err := os.WriteFile(filepath.Join(root, name), []byte(value), 0600); err != nil {
			t.Fatal(err)
		}
	}
	log := filepath.Join(root, "calls")
	mock := `#!/bin/sh
printf '%s %s\n' "$APP_IMAGE" "$*" >> "$SNAPFLOW_TEST_LOG"
case "$APP_IMAGE $*" in *"new-image"*"server worker outbox"*) exit 1;; esac
exit 0
`
	// #nosec G306 -- executable test helper in a private temporary directory.
	if err := os.WriteFile(filepath.Join(bin, "docker"), []byte(mock), 0700); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("bash", "deploy.sh", root, next, "new-image") // #nosec G204 -- all arguments are generated by this test.
	cmd.Env = append(os.Environ(), "PATH="+bin+":"+os.Getenv("PATH"), "SNAPFLOW_TEST_LOG="+log)
	output, runErr := cmd.CombinedOutput()
	if runErr == nil {
		t.Fatal("deployment failure not reported")
	}
	data, err := os.ReadFile(log) // #nosec G304 -- path is inside the test's temporary directory.
	if err != nil {
		t.Fatalf("missing docker log: %v; output=%s", err, output)
	}
	if !strings.Contains(string(data), "old-image ") || !strings.Contains(string(data), "alertbridge") {
		t.Fatalf("rollback calls missing: %s", data)
	}
	value, err := os.ReadFile(filepath.Join(root, "current-image")) // #nosec G304 -- path is inside the test's temporary directory.
	if err != nil || string(value) != "old-image\n" {
		t.Fatalf("release marker: %q %v", value, err)
	}
	if err := os.WriteFile(filepath.Join(root, ".env"), []byte("STORAGE_WRITE_LEGACY=false\n"), 0600); err != nil {
		t.Fatal(err)
	}
	unsafe := exec.Command("bash", "deploy.sh", root, next, "new-image") // #nosec G204 -- test-generated paths.
	unsafe.Env = append(os.Environ(), "PATH="+bin+":"+os.Getenv("PATH"), "SNAPFLOW_TEST_LOG="+log)
	if err := unsafe.Run(); err == nil {
		t.Fatal("unsafe first upgrade accepted")
	}
	after, err := os.ReadFile(log) // #nosec G304 -- path is inside the test's temporary directory.
	if err != nil || string(after) != string(data) {
		t.Fatalf("preflight started containers: %s %v", after, err)
	}
}
